import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import process from "node:process";

const root = process.cwd();
const generatedRelativePath = "lib/release-fingerprint.generated.ts";
const sourceRoots = ["app", "components", "config", "content", "lib", "public"];
const rootFiles = [
  "next.config.ts",
  "package.json",
  "package-lock.json",
  "tsconfig.json",
  "scripts/generate-release-fingerprint.mjs",
];

const normalize = (value) => value.replaceAll("\\", "/");

function collectFiles(relativePath) {
  const absolutePath = path.join(root, relativePath);
  if (!fs.existsSync(absolutePath)) return [];

  const stat = fs.statSync(absolutePath);
  if (stat.isFile()) return [normalize(relativePath)];

  return fs.readdirSync(absolutePath, { withFileTypes: true }).flatMap((entry) => {
    const child = normalize(path.join(relativePath, entry.name));
    if (child === generatedRelativePath) return [];
    if (entry.isDirectory()) return collectFiles(child);
    if (entry.isFile()) return [child];
    return [];
  });
}

export function computeReleaseFingerprint() {
  const files = [
    ...sourceRoots.flatMap(collectFiles),
    ...rootFiles.filter((file) => fs.existsSync(path.join(root, file))),
  ]
    .filter((file) => file !== generatedRelativePath)
    .sort((left, right) => left.localeCompare(right));

  if (files.length === 0) {
    throw new Error("No source files found for release fingerprint");
  }

  const hash = crypto.createHash("sha256");
  for (const relativePath of files) {
    hash.update(relativePath);
    hash.update("\0");
    hash.update(fs.readFileSync(path.join(root, relativePath)));
    hash.update("\0");
  }

  return `web-${hash.digest("hex").slice(0, 24)}`;
}

const fingerprint = computeReleaseFingerprint();

if (process.argv.includes("--print")) {
  process.stdout.write(`${fingerprint}\n`);
} else {
  const outputPath = path.join(root, generatedRelativePath);
  const output = [
    "// Generated by scripts/generate-release-fingerprint.mjs before production builds.",
    "// Do not edit manually; this value identifies the exact web build inputs.",
    `export const WEB_RELEASE_FINGERPRINT = ${JSON.stringify(fingerprint)} as const;`,
    "",
  ].join("\n");
  fs.writeFileSync(outputPath, output, "utf8");
  process.stdout.write(`Generated release fingerprint: ${fingerprint}\n`);
}
